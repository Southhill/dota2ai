-- 获取对线模式的欲望值
-- 游戏时间 10秒 ~ 8分钟 期间对线欲望较高（0.33），之后降低（0.25）
function GetDesire()

	if (DotaTime()>10 and DotaTime() <= 8*60) then
		return 0.33;  -- 前期积极对线
	else
		return 0.25   -- 后期降低对线欲望
	end

end
